function folders = nf_source_dirs(root)
% Only these directories contain NF functions. In particular, do not add
% docs, demos, entire external packages, or MATLAB private directories.
relative = {'fileconversion', 'helpers/robustarithmetic', ...
    'phaseamplitudecoupling', 'phaseamplitudecoupling/hnf_phaseamplitudecoupling', ...
    'preprocessing', 'preprocessing/hnf_preprocessing', ...
    'setutilities', 'setutilities/hnf_setutilities', ...
    'spectralparameterization', 'spectralparameterization/hnf_specparam', ...
    'statistics', 'statistics/hnf_statistics', ...
    'timefrequency', 'timefrequency/hnf_timefrequency'};
folders = cellfun(@(d) fullfile(root, strrep(d, '/', filesep)), ...
    relative, 'UniformOutput', false);
folders = [{root}, folders(cellfun(@isfolder, folders))];
end
