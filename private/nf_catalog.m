function records = nf_catalog()
% Each row belongs to one upstream distribution. Add a row here when an NF
% method gains a third-party call. Start probes with the most distinctive
% function and include the companions needed by the supported NF methods.
% paths are relative to the vendor root ('.' means that directory itself).
% requiredFiles are runtime data, private code, or source files to check on
% disk without exposing those directories or running third-party scripts.
%
% The dependency README lists the first five packages. GitHub snapshots are
% pinned so that a rerun downloads the same layout and APIs we inspected.
% The plugin records below it follow nf_filter, nf_badchans, nf_cleanic,
% nf_thresh and nf_preprocess, including methods outside the default preset.
% EEGLAB's manager name is separate from a plugin's MATLAB function name.
gh = 'https://codeload.github.com/';
sccn = 'https://sccn.ucsd.edu/eeglab/plugins/';
records = entry('ept_tfce', 'EPT-TFCE', '', ...
    [gh 'mensen/ept_tfce-matlab/zip/55d583a0433570eb705cc9794c423f4dcd4a109f'], ...
    'cluster enhancement for the TFCE statistics functions', ...
    {'ept_ChN2'}, {'TFCE/Dependencies'}, ...
    {'TFCE/Dependencies/ept_mex_TFCE.c', 'TFCE/Dependencies/ept_mex_TFCE2D.c', ...
     'TFCE/Dependencies/ept_mex_TFCE3D.c'});
records(end+1) = entry('fminsearchbnd', 'FMINSEARCHBND', '', ...
    ['https://www.mathworks.com/matlabcentral/mlc-downloads/downloads/' ...
     'submissions/8277/versions/5/download/zip'], ...
    'bounded optimization (listed in dependencies/readme_dependencies.txt)', ...
    {'fminsearchbnd', 'fminsearchcon'}, {'.'}, {});
% HAPPE contains its own full EEGLAB distribution and copies of FASTER.
% Only these HAPPE pipeline stages should be visible to NeuroFreq.
records(end+1) = entry('happe', 'HAPPE', '', ...
    [gh 'PINE-Lab/HAPPE/zip/217e646aec2fe9a5159eed43f1131af34d6d39fc'], ...
    'HAPPE+ER bad-channel detection and wavelet cleaning (about 200 MB)', ...
    {'happe_detectBadChans', 'happe_wavThresh', 'assessPipelineStep', 'calcSNR_PSNR'}, ...
    {'scripts/pipeline_steps'}, {});
records(end+1) = entry('made', 'MADE', '', ...
    [gh 'ChildDevLab/MADE-EEG-preprocessing-pipeline/zip/a0b169c07e017151aa6fc17f27f023a129dd80bb'], ...
    'the released adjusted_ADJUST classifier (also uses ADJUST)', ...
    {'adjusted_ADJUST', 'beall_horizontal', 'beall_blink_detection', ...
     'MARA_extract_time_freq_features', 'Spatial_Info_eyes'}, ...
    {'adjusted_adjust_scripts'}, {});
records(end+1) = entry('fieldfun', 'fieldfun', '', ...
    [gh 'WD40andTape/fieldfun/zip/2b53871676e0e2d7a294f6756ff3d4c924817fff'], ...
    'structure utilities (listed in dependencies/readme_dependencies.txt)', ...
    {'fieldfun'}, {'.'}, {});

records(end+1) = entry('firfilt', 'FIRfilt', 'firfilt', [sccn 'firfilt2.8.zip'], ...
    'EEGLAB FIR filtering during preprocessing and ICA training', ...
    {'pop_eegfiltnew', 'firws', 'firfilt'}, {'.'}, {});
% The complete source distribution includes private ASR helpers. The
% official 2.11 plugin-manager ZIP has shipped with an empty private folder.
records(end+1) = entry('clean_rawdata', 'clean_rawdata', 'clean_rawdata', ...
    [gh 'sccn/clean_rawdata/zip/85eab7d22f00f1ed36392c96eb0774752d62bd11'], ...
    'flatline and bad-channel detection, HAPPE+ER, and ASR', ...
    {'pop_clean_rawdata', 'clean_flatlines', 'clean_channels', 'clean_asr', ...
     'asr_calibrate', 'asr_process'}, {'.'}, ...
    {'private/fit_eeg_distribution.m', 'private/hlp_microcache.m'});
% GitHub's clean_rawdata archive leaves the Manopt submodule empty. Its
% gitlink identifies the exact independent archive needed for Riemannian
% ASR. The default Euclidean ASR path works without this component.
records(end+1) = entry('manopt', 'Manopt', '', ...
    [gh 'NicolasBoumal/manopt/zip/6c369671d8834aa28f7e222c7d89c5f216e6953d'], ...
    'the optional Riemannian mode of clean_rawdata ASR', ...
    {'grassmannfactory','manoptsolve','trustregions','StoreDB'}, ...
    {'.','manopt/manifolds/grassmann','manopt/tools','manopt/core', ...
     'manopt/solvers/trustregions'}, {});
prepPaths = {'.', 'utilities', 'derived', 'extracted', 'interface', ...
    'reporting', 'reporting/helpers', 'utilities/blasst', ...
    'utilities/chronux_2_modified/spectral_analysis/continuous', ...
    'utilities/chronux_2_modified/spectral_analysis/helper'};
records(end+1) = entry('preppipeline', 'PREP', 'PrepPipeline', [sccn 'PrepPipeline0.57.0.zip'], ...
    'the PREP preclean and bad-channel stages', ...
    {'prepPipeline', 'getPrepVersion', 'removeTrend', 'findNoisyChannels'}, prepPaths, {});
records(end+1) = entry('faster', 'FASTER', 'FASTER', [sccn 'FASTER1.2.4.zip'], ...
    'channel, IC, and epoch artifact detection and interpolation', ...
    {'channel_properties', 'component_properties', 'epoch_properties', ...
     'single_epoch_channel_properties', 'h_epoch_interp_spl', 'min_z', ...
     'hurst_exponent', 'distancematrix'}, {'.'}, {});
% eeg_checkset calls dipfitdefs while handling EEG.dipfit metadata.
records(end+1) = entry('dipfit', 'DIPFIT', 'dipfit', [sccn 'dipfit5.6.zip'], ...
    'EEGLAB validation of dipole-model metadata', ...
    {'dipfitdefs','pop_dipfit_settings'}, ...
    {'.','standard_BEM','standard_BEM/elec','standard_BEM/skin','standard_BESA'}, {});
% The release ZIP includes the trained network and its MatConvNet submodule.
% activate_matconvnet manages its own subpaths at classification time.
records(end+1) = entry('iclabel', 'ICLabel', 'ICLabel', [sccn 'ICLabel1.7.zip'], ...
    'ICA component classification and probability-based flagging', ...
    {'pop_iclabel','pop_icflag','iclabel','activate_matconvnet'}, {'.'}, ...
    {'netICL.mat','matconvnet/matlab/vl_setupnn.m'});
records(end+1) = entry('adjust', 'ADJUST', 'Adjust', [sccn 'ADJUST1.1.1.zip'], ...
    'official ADJUST classification and the feature functions used by MADE', ...
    {'ADJUST','compute_GD_feat','computeSED_NOnorm','computeSAD','EM', ...
     'trim_and_mean','trim_and_max'}, {'.'}, {});
records(end+1) = entry('mara', 'MARA', 'MARA', [sccn 'MARA1.2.zip'], ...
    'official MARA component classification', {'MARA'}, {'.'}, ...
    {'fv_training_MARA.mat','inv_matrix_icbm152.mat'});
records(end+1) = entry('amica', 'AMICA', 'AMICA', [sccn 'amica1.7.zip'], ...
    'AMICA decomposition (also needs its platform executable)', ...
    {'pop_runamica','runamica15','loadmodout15'}, {'.'}, {});
records(end+1) = entry('picard', 'Picard', 'PICARD', [sccn 'PICARD2.0.zip'], ...
    'standard and orthogonal Picard ICA', ...
    {'picard','picardo','picard_standard','whitening'}, {'.'}, {});
records(end+1) = entry('gedai', 'GEDAI', 'GEDAI', ...
    'https://github.com/neurotuning/GEDAI-master/releases/download/v1.7/GEDAI-master-v1.7.zip', ...
    'GEDAI precleaning with the v1.7 API required by nf_preprocess', ...
    {'GEDAI','eeg_interp_GEDAI'}, {'.','auxiliaries'}, ...
    {'auxiliaries/fsavLEADFIELD_4_GEDAI.mat'});
records(end).pluginVersion = '1.7';
end

function record = entry(key, name, plugin, url, features, probes, paths, requiredFiles)
record = struct('key',key, 'name',name, 'kind','bundle', 'plugin',plugin, ...
    'url',url, 'features',features, 'probes',{probes}, 'paths',{paths}, ...
    'requiredFiles',{requiredFiles}, 'pluginVersion','', 'folder','');
% Set folder to a path relative to NF if a future distribution vendors this
% package in the repository. Current releases provide external downloads.
if ~isempty(plugin), record.kind = 'plugin'; end
end
