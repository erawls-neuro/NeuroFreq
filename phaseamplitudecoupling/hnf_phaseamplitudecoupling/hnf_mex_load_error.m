function yes = hnf_mex_load_error(err)
% A missing runtime/link library can prevent loading an otherwise valid MEX.
% Native argument, allocation, and algorithm errors must reach their caller.
yes = strcmpi(err.identifier,'MATLAB:invalidMEXFile') || ...
    (exist('OCTAVE_VERSION','builtin') && ~isempty(regexp(err.message, ...
        '(failed to load|failed to install|cannot open shared object file|invalid ELF header|undefined symbol:)', ...
        'once')));
end
